def _scan_grep_fallback(src_dir: str, output_dir: str = ".") -> ScanResult:
    """Text-grep based scan: no libclang needed.

    Scans .h files for widget member declarations, .cpp files for
    setObjectName/setAccessibleName calls. Less precise than libclang
    but works without any C++ parser.
    """
    root = Path(src_dir)
    if not root.is_dir():
        logger.error("Source directory not found: %s", src_dir)
        return ScanResult(source_dir=src_dir)

    # Collect all widget member declarations from .h files
    # Pattern: "Type *variable;" or "Type variable;" where Type is in our sets
    import re
    widgets: dict[str, WidgetInstance] = {}
    class_name = ""

    # Build union of all known type names for regex
    all_types = _INTERACTIVE_CLASSES | _DECORATIVE_CLASSES | _NON_WIDGET_INTERACTIVE | _LAYOUT_CLASSES
    # Sort by length descending so longer names match first
    type_patterns = sorted(all_types, key=len, reverse=True)
    type_re = re.compile(r"(" + "|".join(re.escape(t) for t in type_patterns) + r")\s*\*?\s*(\w+)\s*[;=]")

    # Also match custom types from TypeDatabase
    custom_types = list(_TYPE_DB._custom_types.keys()) if hasattr(_TYPE_DB, '_custom_types') else []
    if custom_types:
        custom_re = re.compile(r"(" + "|".join(re.escape(t) for t in custom_types) + r")\s*\*?\s*(\w+)\s*[;=]")
    else:
        custom_re = None

    header_files = sorted(root.rglob("*.h"))
    for hf in header_files:
        if any(part in {"tests", "test", "build", ".git", "debian", "3rdparty"} for part in hf.parts):
            continue
        try:
            content = hf.read_text(errors="replace")
        except Exception:
            continue
        # Track class name
        for line in content.splitlines():
            ls = line.strip()
            if ls.startswith("class ") and "{" in ls:
                cn = ls.split("{")[0].replace("class", "").strip().split()[0] if ls.split("{")[0].replace("class", "").strip() else ""
                if cn:
                    class_name = cn
        # Find widget declarations
        for m in type_re.finditer(content):
            typ, var = m.group(1), m.group(2)
            if var and var not in widgets:
                line_no = content[:m.start()].count("\n") + 1
                rel_path = str(hf.relative_to(root))
                widgets[var] = WidgetInstance(
                    variable=var, type_name=typ + "*",
                    source_file=rel_path, class_name=class_name,
                    line=line_no, role=_map_role(typ),
                )
        if custom_re:
            for m in custom_re.finditer(content):
                typ, var = m.group(1), m.group(2)
                if var and var not in widgets:
                    line_no = content[:m.start()].count("\n") + 1
                    rel_path = str(hf.relative_to(root))
                    widgets[var] = WidgetInstance(
                        variable=var, type_name=typ + "*",
                        source_file=rel_path, class_name=class_name,
                        line=line_no, role=_map_role(typ),
                    )

    # Find setObjectName/setAccessibleName calls in .cpp files
    name_calls: dict[str, set[tuple[str, str]]] = {}
    all_named_vars: set[str] = set()
    call_re = re.compile(r"(\w+)\s*->\s*(setObjectName|setAccessibleName)\s*\(\s*\"([^\"]*)\"\s*\)")

    cpp_files = sorted(root.rglob("*.cpp"))
    for cf in cpp_files:
        if any(part in {"tests", "test", "build", ".git", "debian", "3rdparty"} for part in cf.parts):
            continue
        try:
            content = cf.read_text(errors="replace")
        except Exception:
            continue
        for m in call_re.finditer(content):
            var, call_type, name_val = m.group(1), m.group(2), m.group(3)
            all_named_vars.add(var)
            if var in widgets:
                if var not in name_calls:
                    name_calls[var] = set()
                name_calls[var].add((call_type, name_val))

    # Classify
    all_ok: list[WidgetInstance] = []
    all_gaps: list[WidgetInstance] = []
    for var_name, inst in widgets.items():
        if var_name in name_calls:
            for call_type, name_val in name_calls[var_name]:
                if call_type == "setObjectName":
                    inst.has_object_name = True
                    inst.existing_object_name = name_val
                elif call_type == "setAccessibleName":
                    inst.has_accessible_name = True
                    inst.existing_accessible_name = name_val
        is_interactive = _is_interactive_type(inst.type_name)
        is_decorative = _is_decorative_type(inst.type_name)
        is_layout = _is_layout_type(inst.type_name)
        if is_layout:
            continue
        if is_decorative and not inst.has_object_name and not inst.has_accessible_name:
            continue
        if inst.has_object_name or inst.has_accessible_name:
            if is_interactive and not _is_non_widget_interactive(inst.type_name):
                if inst.has_object_name and inst.has_accessible_name:
                    all_ok.append(inst)
                else:
                    all_gaps.append(inst)
            else:
                all_ok.append(inst)
        elif is_interactive:
            all_gaps.append(inst)

    # Cross-file merge
    still_gaps: list[WidgetInstance] = []
    for g in all_gaps:
        if g.variable in all_named_vars:
            all_ok.append(g)
        else:
            still_gaps.append(g)
    all_gaps = still_gaps

    all_ok.sort(key=lambda w: (w.source_file, w.line, w.variable))
    all_gaps.sort(key=lambda w: (w.source_file, w.line, w.variable))

    result = ScanResult(
        source_dir=src_dir, total_files=len(cpp_files) + len(header_files),
        parsed_files=len(cpp_files) + len(header_files),
        widgets=all_ok + all_gaps, ok_widgets=all_ok, gap_widgets=all_gaps,
    )
    _write_outputs(result, output_dir)
    return result


# ── 主扫描编排 ──────────────────────────────────────────────────
def scan_source(src_dir: str, build_dir: str | None = None,
                compile_commands: str | None = None,
                output_dir: str = ".", mode: str = "auto") -> ScanResult:
    """Scan C++ source for AT-SPI name coverage.

    Args:
        src_dir: Source directory.
        build_dir: Build directory (for compile_commands.json).
        compile_commands: Path to compile_commands.json.
        output_dir: Output directory.
        mode: 'auto' (try libclang, fallback to grep), 'libclang' (only libclang),
              'grep' (only text grep, no libclang).
    """
    root = Path(src_dir)
    if not root.is_dir():
        logger.error("Source directory not found: %s", src_dir)
        return ScanResult(source_dir=src_dir)

    # Determine mode
    use_libclang = mode == "libclang" or (mode == "auto" and _LIBCLANG_READY and _LIBCLANG_IMPORT_OK)
    use_grep = mode == "grep" or (mode == "auto" and not (_LIBCLANG_READY and _LIBCLANG_IMPORT_OK))

    if use_grep:
        logger.info("Using grep fallback mode (no libclang)")
        return _scan_grep_fallback(src_dir, output_dir)

    if not use_libclang:
        logger.error("No scan method available. Install libclang or use --mode grep")
        return ScanResult(source_dir=src_dir)

    # ── libclang path (original) ──
    file_flags: dict[str, list[str]] | None = None
    if compile_commands:
        file_flags = _load_compile_commands(compile_commands)
    elif build_dir:
        file_flags = _load_compile_commands(str(Path(build_dir) / "compile_commands.json"))

    extra_args = ["-x", "c++", "-std=c++17", "-fPIC"]
    extra_args.extend(_get_cxx_stdlib_flags())

    project_includes: list[str] = []
    if file_flags:
        src_str = str(root)
        seen = set()
        for _file, flags in file_flags.items():
            for f in flags:
                if f.startswith("-I") and f not in seen:
                    seen.add(f)
                    inc_path = f[2:]
                    if inc_path and (inc_path.startswith(src_str) or src_str in inc_path):
                        project_includes.append(f)

    _TYPE_DB.resolve_custom_types(src_dir, project_includes)

    extensions = {".cpp", ".cxx", ".cc"}
    _SKIP_DIRS = {"tests", "test", "autotests", "autotest",
                   "build", "Build", "builddir", "_build",
                   "cmake-build", "CMakeFiles", ".cmake",
                   "debian", ".git", "3rdparty", "thirdparty", "third_party"}
    _SKIP_PREFIXES = ("test_", "moc_", "mocs_", "ui_", "qrc_")

    all_files: list[Path] = []
    for p in root.rglob("*"):
        if p.suffix not in extensions:
            continue
        if any(part in _SKIP_DIRS for part in p.parts):
            continue
        if p.stem.startswith(_SKIP_PREFIXES):
            continue
        all_files.append(p)
    all_files.sort()

    if not all_files:
        logger.warning("No C++ source files found in %s", src_dir)
        return ScanResult(source_dir=src_dir)

    task_items: list[tuple[str, str, list[str]]] = []
    for p in all_files:
        abs_path = str(p)
        rel_path = str(p.relative_to(root))
        if file_flags and abs_path in file_flags:
            flags = file_flags[abs_path]
            extra_includes = [f for f in extra_args if f.startswith("-I") or f.startswith("-isystem")]
            for inc in extra_includes:
                if inc not in flags:
                    flags.append(inc)
        else:
            flags = extra_args
        task_items.append((abs_path, rel_path, flags))

    total = len(task_items)
    n_workers = min(os.cpu_count() or 4, 8)
    batch_size = max(1, (total + n_workers - 1) // n_workers)
    batches = [task_items[i:i + batch_size] for i in range(0, total, batch_size)]

    all_ok: list[WidgetInstance] = []
    all_gaps: list[WidgetInstance] = []
    global_named_vars: set[str] = set()
    parsed = 0
    failed = 0
    done = 0

    if n_workers > 1:
        with multiprocessing.Pool(n_workers, initializer=_worker_init, initargs=(extra_args,)) as pool:
            for batch_results in pool.imap_unordered(_worker_scan_batch, batches):
                for rel_path, ok_list, gap_list, named_vars, error in batch_results:
                    if error:
                        logger.warning("Failed to parse %s: %s", rel_path, error)
                        failed += 1
                    else:
                        parsed += 1
                    all_ok.extend(ok_list)
                    all_gaps.extend(gap_list)
                    global_named_vars.update(named_vars)
                    done += 1
    else:
        for batch in batches:
            for rel_path, ok_list, gap_list, named_vars, error in _worker_scan_batch(batch):
                if error:
                    logger.warning("Failed to parse %s: %s", rel_path, error)
                    failed += 1
                else:
                    parsed += 1
                all_ok.extend(ok_list)
                all_gaps.extend(gap_list)
                global_named_vars.update(named_vars)
                done += 1

    # Cross-file merge
    still_gaps: list[WidgetInstance] = []
    for g in all_gaps:
        if g.variable in global_named_vars:
            all_ok.append(g)
        else:
            still_gaps.append(g)
    all_gaps = still_gaps

    all_ok.sort(key=lambda w: (w.source_file, w.line, w.variable))
    all_gaps.sort(key=lambda w: (w.source_file, w.line, w.variable))

    result = ScanResult(
        source_dir=src_dir, total_files=total, parsed_files=parsed,
        failed_files=failed, widgets=all_ok + all_gaps,
        ok_widgets=all_ok, gap_widgets=all_gaps,
    )

    _write_outputs(result, output_dir)
    return result


def _widget_to_dict(w: WidgetInstance) -> dict[str, Any]:
    return {
        "variable": w.variable, "type": w.type_name,
        "source_file": w.source_file, "class_name": w.class_name,
        "line": w.line, "instantiation": w.instantiation,
        "has_object_name": w.has_object_name,
        "has_accessible_name": w.has_accessible_name,
        "existing_object_name": w.existing_object_name,
        "existing_accessible_name": w.existing_accessible_name,
        "display_text": w.display_text, "role": w.role,
        "context": w.context, "is_action": w.is_action,
        "action_owner": w.action_owner,
    }


def _write_outputs(result: ScanResult, output_dir: str) -> None:
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    # pre_scan_gaps.yaml
    gaps_data = {
        "version": "1.0",
        "source_dir": result.source_dir,
        "total_files": result.total_files,
        "parsed_files": result.parsed_files,
        "failed_files": result.failed_files,
        "gaps": [_widget_to_dict(w) for w in result.gap_widgets],
    }
    gaps_path = out / "pre_scan_gaps.yaml"
    import yaml
    with open(gaps_path, "w", encoding="utf-8") as f:
        yaml.dump(gaps_data, f, default_flow_style=False, allow_unicode=True, sort_keys=False)
    logger.info("Written %s (%d gaps)", gaps_path, len(result.gap_widgets))

    # pre_scan_ok.yaml
    ok_data = {
        "version": "1.0",
        "source_dir": result.source_dir,
        "widgets": [_widget_to_dict(w) for w in result.ok_widgets],
    }
    ok_path = out / "pre_scan_ok.yaml"
    with open(ok_path, "w", encoding="utf-8") as f:
        yaml.dump(ok_data, f, default_flow_style=False, allow_unicode=True, sort_keys=False)
    logger.info("Written %s (%d ok)", ok_path, len(result.ok_widgets))

    # coverage summary
    total = len(result.widgets)
    ok_count = len(result.ok_widgets)
    gap_count = len(result.gap_widgets)
    coverage = (ok_count / total * 100) if total else 0.0
    logger.info("Coverage: %d/%d = %.1f%% (%d gaps)", ok_count, total, coverage, gap_count)


