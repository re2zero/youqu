def _is_ui_type(type_name: str) -> bool:
    base = type_name.replace(" *", "").replace("&", "").split("<")[0].strip()
    if _TYPE_DB.is_ui_type(base):
        return True
    if base in _ALL_UI_CLASSES:
        return True
    for cls in _ALL_UI_CLASSES:
        if base.endswith(cls):
            return True
    return False


