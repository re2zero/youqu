def main():
    parser = argparse.ArgumentParser(description="AT-SPI C++ coverage scanner (standalone)")
    parser.add_argument("--src", required=True, help="Source directory")
    parser.add_argument("--build", help="Build directory (for compile_commands.json)")
    parser.add_argument("--compile-commands", help="Path to compile_commands.json")
    parser.add_argument("--output", "-o", default=".", help="Output directory")
    parser.add_argument("--mode", default="auto", choices=["auto", "libclang", "grep"],
                        help="Scan mode: auto (try libclang, fallback grep), libclang (only), grep (text only)")
    args = parser.parse_args()

    result = scan_source(
        src_dir=args.src, build_dir=args.build,
        compile_commands=args.compile_commands, output_dir=args.output,
        mode=args.mode,
    )
    return 0 if result.parsed_files > 0 else 1


